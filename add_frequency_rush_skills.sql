-- 1. Remember which fact each answer was ("mul:7x8"), for My Missed Words
--    and the Fact Wall later. Sort answers have no vocabulary word, so
--    word_id must allow nulls (existing sort_bins answers already need this).
ALTER TABLE frequency_rush_attempts
  ADD COLUMN IF NOT EXISTS item_key TEXT;

ALTER TABLE frequency_rush_attempts
  ALTER COLUMN word_id DROP NOT NULL;

CREATE INDEX IF NOT EXISTS frequency_rush_attempts_item_key_idx
  ON frequency_rush_attempts (item_key);

-- 2. The six fact sets. The questions are generated by the site
--    (lib/frequencyRushSkills.js), so there is no content to load.
--    They appear under Math, Grade 3, in the assign page.
INSERT INTO cases (standard, title, engine, grade, subject, unit) VALUES
  ('MA.3.4F-FR-MUL', 'Frequency Rush: Multiplication Facts to 10 × 10',          'frequency_rush', 3, 'Math', 'skill'),
  ('MA.3.4F-FR-DIV', 'Frequency Rush: Division Facts',                            'frequency_rush', 3, 'Math', 'skill'),
  ('MA.3.4F-FR-MIX', 'Frequency Rush: Multiplication and Division Facts',         'frequency_rush', 3, 'Math', 'skill'),
  ('MA.3.4A-FR-ADD', 'Frequency Rush: Addition Facts (Foundation)',               'frequency_rush', 3, 'Math', 'skill'),
  ('MA.3.4A-FR-SUB', 'Frequency Rush: Subtraction Facts (Foundation)',            'frequency_rush', 3, 'Math', 'skill'),
  ('MA.3.4A-FR-MIX', 'Frequency Rush: Addition and Subtraction Facts (Foundation)', 'frequency_rush', 3, 'Math', 'skill')
ON CONFLICT (standard) DO UPDATE SET
  title = EXCLUDED.title,
  engine = EXCLUDED.engine,
  grade = EXCLUDED.grade,
  subject = EXCLUDED.subject,
  unit = EXCLUDED.unit;

UPDATE cases SET
  learning_target = 'I can recall multiplication facts up to 10 × 10 quickly and accurately.',
  lesson_summary = 'Fast multiplication facts in the run game. Wrong answers are near misses, like the fact next door. New facts every replay.'
WHERE standard = 'MA.3.4F-FR-MUL';

UPDATE cases SET
  learning_target = 'I can recall division facts by thinking of the matching multiplication fact.',
  lesson_summary = 'Fast division facts in the run game, using facts up to 10 × 10. New facts every replay.'
WHERE standard = 'MA.3.4F-FR-DIV';

UPDATE cases SET
  learning_target = 'I can switch between multiplication and division facts quickly.',
  lesson_summary = 'Multiplication and division facts mixed half and half in the run game. New facts every replay.'
WHERE standard = 'MA.3.4F-FR-MIX';

UPDATE cases SET
  learning_target = 'I can recall addition facts with sums to 20 quickly.',
  lesson_summary = 'Foundation practice: fast addition facts (1 + 1 to 10 + 10) in the run game. Tagged 3.4A.'
WHERE standard = 'MA.3.4A-FR-ADD';

UPDATE cases SET
  learning_target = 'I can recall subtraction facts from 20 quickly.',
  lesson_summary = 'Foundation practice: fast subtraction facts in the run game. Tagged 3.4A.'
WHERE standard = 'MA.3.4A-FR-SUB';

UPDATE cases SET
  learning_target = 'I can switch between addition and subtraction facts quickly.',
  lesson_summary = 'Foundation practice: addition and subtraction facts mixed in the run game. Tagged 3.4A.'
WHERE standard = 'MA.3.4A-FR-MIX';
