// Signal Defense — 4.10C, Weather vs. Climate (Grade 4 Science).
// Grade 4 expansion, Sept 16, 2026.
//
// TEKS 4.10C verbatim (TEA adopted grade 4 science TEKS): "differentiate
// between weather and climate"
//
// Verb: DIFFERENTIATE — a single comparison verb, and the narrowest
// standard in the grade 4 set. That makes the bank easy to write badly: a
// pile of "what is climate?" definitions would technically be on topic while
// never asking a student to tell the two apart. So nearly every item here
// puts a specific example in front of the student and asks which one it is,
// or contrasts the two directly.
//
// The distinction that carries it: TIME SCALE. Weather is what is happening
// now or over days; climate is the pattern over many years. Items lean on
// that repeatedly because it is the thing students actually confuse.
//
// Worth knowing: TEA's 2024-2025 STAAR grade 5 comparison lists 4.10C among
// the standards assessed on the GRADE 5 test as a supporting standard, so
// this bank is grade 5 review as well as grade 4 instruction.

