// Rewrites lib/cleardecode/ruins/index.js from the ruin files on disk.
// Run after adding a ruin: node tools/cleardecode-registry.cjs
const fs = require("fs");
const path = require("path");
const dir = path.join(__dirname, "../lib/cleardecode/ruins");
const order = (id) => (id.charCodeAt(0) - 65) * 100 + Number(id.slice(1));
const ids = fs.readdirSync(dir).filter((f) => /^[A-K]\d\.js$/.test(f)).map((f) => f.replace(".js", "")).sort((a, b) => order(a) - order(b));
const out = `// Generated by tools/cleardecode-registry.cjs. Do not edit by hand.
${ids.map((id) => `import ${id} from "./${id}.js";`).join("\n")}

const RUIN_CONTENT = { ${ids.join(", ")} };
export default RUIN_CONTENT;
`;
fs.writeFileSync(path.join(dir, "index.js"), out);
console.log(`Registered ${ids.length} ruins: ${ids.join(", ")}`);
